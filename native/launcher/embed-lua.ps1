# Writes browser_lua.h (the in-game browser script as a C++ string) into the build output.
# MSVC limits one string literal to about 16 KB, so the script is split at line breaks into
# several raw-string pieces; adjacent literals are joined by the compiler.
param([Parameter(Mandatory)][string]$Source, [Parameter(Mandatory)][string]$Out)
$ErrorActionPreference = 'Stop'
$lines = [IO.File]::ReadAllLines($Source)
$text = $lines -join "`n"
if ($text.Contains(')lua"')) { throw "$Source must not contain the raw-string delimiter )lua`"" }
$pieces = New-Object System.Collections.Generic.List[string]
$piece = New-Object System.Text.StringBuilder
foreach ($line in $lines) {
    if ($piece.Length + $line.Length + 1 -gt 12000) { $pieces.Add($piece.ToString()); [void]$piece.Clear() }
    [void]$piece.Append($line).Append("`n")
}
if ($piece.Length) { $pieces.Add($piece.ToString()) }
$header = New-Object System.Text.StringBuilder
[void]$header.Append("// Generated by embed-lua.ps1 from lua/browser.lua; do not edit.`n#pragma once`nstatic const char kBrowserLua[]=")
for ($i = 0; $i -lt $pieces.Count; $i++) {
    if ($i) { [void]$header.Append("`n") }
    [void]$header.Append('R"lua(').Append($pieces[$i]).Append(')lua"')
}
[void]$header.Append(";`n")
[IO.File]::WriteAllText((Join-Path $Out 'browser_lua.h'), $header.ToString(), (New-Object System.Text.UTF8Encoding $false))
